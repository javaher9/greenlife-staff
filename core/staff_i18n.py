def static_ui_pairs(language):
    """Return exact Persian UI phrase -> localized phrase pairs."""
    language = normalize_ui_language(language)
    if language == 'fa':
        return ()
    pairs = {}
    # Main keyed catalog.
    target = TRANSLATIONS.get(language, {})
    for key, fa_text in FA.items():
        localized = target.get(key)
        if isinstance(fa_text, str) and isinstance(localized, str) and localized != fa_text:
            if '{' not in fa_text and '}' not in fa_text:
                pairs[fa_text] = localized
    # Model/display choices.
    for namespace in CHOICES.values():
        for labels in namespace.values():
            fa_text = labels.get('fa')
            localized = labels.get(language)
            if fa_text and localized and localized != fa_text:
                pairs[fa_text] = localized
    # Legacy exact phrases.
    for fa_text, labels in STATIC_UI_PHRASES.items():
        localized = labels.get(language)
        if localized:
            pairs[fa_text] = localized
    return tuple(sorted(pairs.items(), key=lambda item: len(item[0]), reverse=True))


def normalize_ui_language(value):
    code = (value or '').strip().lower().replace('_', '-').split('-', 1)[0]
    return code if code in SUPPORTED_UI_LANGUAGE_CODES else 'fa'


def ui_direction(language):
    return 'rtl' if normalize_ui_language(language) == 'fa' else 'ltr'


def translate(key, language='fa', **kwargs):
    language = normalize_ui_language(language)
    text = TRANSLATIONS.get(language, FA).get(key)
    if text is None:
        text = FA.get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, ValueError, IndexError):
            pass
    return text


def translate_country_name(country, language='fa'):
    language=normalize_ui_language(language)
    code=(getattr(country,'code','') or '').upper()
    names=COUNTRY_UI_NAMES.get(code,{})
    return names.get(language) or names.get('en') or getattr(country,'name_local',None) or getattr(country,'name',None) or code


def translate_choice(namespace, value, language='fa', fallback=''):
    language = normalize_ui_language(language)
    item = CHOICES.get(namespace, {}).get(str(value), {})
    return item.get(language) or item.get('fa') or fallback or str(value or '')


